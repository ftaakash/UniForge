<#
.SYNOPSIS
    Regenerates the committed Task D benchmark report and the results section of
    docs/performance.md in one step.

.DESCRIPTION
    1. Deletes the previous results/benchmarks/bench_<date>.* files (report, plots, sidecar).
    2. Runs `uniforge_cli bench --report --out results` (10000 cases x 8000 elements,
       1 warm-up + 5 timed reps for p = 1, 2, 4).
    3. Replaces the text between the BENCH:BEGIN / BENCH:END markers in docs/performance.md
       with the new report (headings demoted one level) and links to the new plots.

    Run it on a quiet machine (close builds, browsers, games; plugged in). Wrapper only: all
    measuring and formatting is done by uniforge_cli.

.PARAMETER Cli
    Path to uniforge_cli.exe (default: the Release build of the windows-msvc preset).

.PARAMETER Status
    Optional label written at the top of the report, e.g. "PROVISIONAL: machine under load".
    Leave empty for the official run.

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File tools/bench_report.ps1
#>
param(
    [string]$Cli = "build/windows-msvc/bin/Release/uniforge_cli.exe",
    [string]$Status = ""
)
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

if (-not (Test-Path $Cli)) {
    throw "uniforge_cli not found at '$Cli'. Build first: cmake --build --preset windows-release"
}

$benchDir = Join-Path $root "results/benchmarks"
Get-ChildItem $benchDir -File -Filter "bench_20*" -ErrorAction SilentlyContinue |
    Remove-Item -Force

$cliArgs = @("bench", "--report", "--out", "results")
if ($Status) { $cliArgs += @("--status", $Status) }
& $Cli @cliArgs
if ($LASTEXITCODE -ne 0) { throw "uniforge_cli bench exited with $LASTEXITCODE" }

$report = Get-ChildItem $benchDir -File -Filter "bench_20*.md" | Sort-Object Name | Select-Object -Last 1
if (-not $report) { throw "no bench_<date>.md written" }
$stem = [IO.Path]::GetFileNameWithoutExtension($report.Name)

# Report body without its H1, headings one level down, plus the plots.
$md = [IO.File]::ReadAllText($report.FullName) -replace "`r`n", "`n"
$body = ($md -split "`n", 2)[1].Trim() -replace '(?m)^## ', '### '
$plots = @"

![Compute time vs workers](../results/benchmarks/${stem}_timing.svg)

![Speedup vs workers](../results/benchmarks/${stem}_speedup.svg)

![Efficiency vs workers](../results/benchmarks/${stem}_efficiency.svg)

Source files: [``$stem.md``](../results/benchmarks/$stem.md),
[``$stem.csv``](../results/benchmarks/$stem.csv), [``$stem.json``](../results/benchmarks/$stem.json).
"@
$generated = "<!-- BENCH:BEGIN (generated by tools/bench_report.ps1, do not edit by hand) -->`n" +
             $body + "`n" + $plots + "`n<!-- BENCH:END -->"

$docPath = Join-Path $root "docs/performance.md"
$doc = [IO.File]::ReadAllText($docPath) -replace "`r`n", "`n"
$pattern = '(?s)<!-- BENCH:BEGIN.*?<!-- BENCH:END -->'
if ($doc -notmatch $pattern) { throw "BENCH:BEGIN / BENCH:END markers missing in docs/performance.md" }
$doc = [regex]::Replace($doc, $pattern, [Text.RegularExpressions.MatchEvaluator]{ param($m) $generated })
[IO.File]::WriteAllText($docPath, $doc, (New-Object Text.UTF8Encoding($false)))

Write-Host "Updated docs/performance.md from results/benchmarks/$stem.md"
